#!/usr/bin/env node
/**
 * 流水线端到端校验：用本地 file:// 假源 + 注入的假探测器跑完整 runPipeline，
 * 不联网、不起内核，确认「抓取 -> 规范化 -> 去重 -> 排序截断 -> 落盘」整条链路正确。
 * 运行：node test/pipeline.test.js
 */
'use strict';

const fs = require('fs');
const path = require('path');
const assert = require('assert');
const YAML = require('js-yaml');

const lib = require(path.join(__dirname, '..', 'fetch.js'));

const workDir = path.join(__dirname, '..', '.cache', 'pipeline-test');
fs.rmSync(workDir, { recursive: true, force: true });
fs.mkdirSync(workDir, { recursive: true });

const fixture = `proxies:
  - {name: "🇺🇸 美国 01", type: vmess, server: us1.example.com, port: 443, uuid: u1, tls: true, skipCertVerify: true}
  - {name: "🇺🇸 美国 01 dup", type: vmess, server: us1.example.com, port: 443, uuid: u1, tls: true, udp: true}
  - {name: "🇯🇵 JP 东京", type: vmess, server: jp1.example.com, port: 443, uuid: u2, tls: true}
  - {name: "🇭🇰 HK 香港", type: trojan, server: hk1.example.com, port: 443, password: p1}
  - {name: "🇺🇸 US 慢", type: ss, server: us2.example.com, port: 8388, cipher: aes-128-gcm, password: p2}
  - {name: "不支持的协议", type: magic, server: bad.example.com, port: 443}
`;

const srcPath = path.join(workDir, 'fixture-nodes.yaml');
fs.writeFileSync(srcPath, fixture, 'utf8');
const srcUrl = `file://${srcPath.replace(/\\/g, '/')}`;

const sourcesPath = path.join(workDir, 'sources.yaml');
fs.writeFileSync(sourcesPath, `sources:\n  - name: 本地假源\n    url: ${srcUrl}\n    enabled: true\n`, 'utf8');

const outClient = path.join(workDir, 'out', 'free-nodes.yaml');
const outProvider = path.join(workDir, 'out', 'providers', 'free-nodes.yaml');

// 假探测：us1 200ms、jp1 80ms、hk1 400ms、us2 1500ms（超 MAX_DELAY 应被丢掉）
const DELAYS = {
  'us1.example.com': 200,
  'jp1.example.com': 80,
  'hk1.example.com': 400,
  'us2.example.com': 1500,
};

async function fakeProbe(entries) {
  return entries
    .filter((e) => DELAYS[e.proxy.server] !== undefined)
    .map((e) => ({ ...e, delay: DELAYS[e.proxy.server] }));
}

(async () => {
  const result = await lib.runPipeline({
    sourcesFile: sourcesPath,
    outClient,
    outProvider,
    probe: fakeProbe,
  });

  assert.strictEqual(result.sourceCount, 1);
  assert.strictEqual(result.rawCount, 6, '应解析出 6 个原始节点');
  assert.strictEqual(result.kept.length, 3, 'us2 延迟超阈值应被过滤');

  const providerDoc = YAML.load(fs.readFileSync(outProvider, 'utf8'));
  assert.deepStrictEqual(Object.keys(providerDoc), ['proxies'], 'provider 文件只能有 proxies');
  assert.strictEqual(providerDoc.proxies.length, 3);

  // 按延迟升序：jp1 80 -> us1 200 -> hk1 400
  assert.deepStrictEqual(
    providerDoc.proxies.map((p) => p.server),
    ['jp1.example.com', 'us1.example.com', 'hk1.example.com']
  );
  assert.deepStrictEqual(
    providerDoc.proxies.map((p) => p.name),
    ['🇯🇵JP-001·80ms', '🇺🇸US-001·200ms', '🇭🇰HK-001·400ms']
  );

  // 重复节点只留一个
  assert.strictEqual(
    providerDoc.proxies.filter((p) => p.server === 'us1.example.com').length,
    1
  );

  // 规范化结果落到最终产物里
  const us1 = providerDoc.proxies.find((p) => p.server === 'us1.example.com');
  assert.strictEqual(us1['skip-cert-verify'], true);
  assert.strictEqual(us1.skipCertVerify, undefined);
  assert.strictEqual(us1.udp, true);

  const rawClient = fs.readFileSync(outClient, 'utf8');
  assert.ok(rawClient.startsWith('# generated by proxy-fetcher at'), '缺少生成时间头');
  assert.ok(/nodes: 3/.test(rawClient), '头部节点数应为 3');

  const clientDoc = YAML.load(rawClient);
  assert.strictEqual(clientDoc.proxies.length, 3);
  const select = clientDoc['proxy-groups'].find((g) => g.name === '节点选择');
  assert.deepStrictEqual(select.proxies, [
    '自动选择',
    '🇯🇵JP-001·80ms',
    '🇺🇸US-001·200ms',
    '🇭🇰HK-001·400ms',
  ]);

  fs.rmSync(workDir, { recursive: true, force: true });
  console.log('  ok   runPipeline 端到端（抓取/去重/过滤/排序/落盘）通过');
})().catch((err) => {
  console.error(`  FAIL runPipeline 端到端: ${err.message}`);
  process.exit(1);
});
