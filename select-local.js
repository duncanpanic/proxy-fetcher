#!/usr/bin/env node
/**
 * select-local.js —— 用本机网络重新筛选候选池
 *
 * 为什么需要它：fetch.js 的探测跑在 GitHub Actions runner 上（美国/欧洲机房），
 * 它判活的节点只代表「从机房能连」，和你在中国家里/公司的连通性几乎无关。
 * 同一份产物在 runner 上 120/120 通过，在本机可能只有个位数能连。
 *
 * 所以：抓源留在 CI（机房能访问 raw.githubusercontent），
 *      探测搬回本机（只有你的网络才代表你的体验）。
 *
 * 用法：
 *   npm install js-yaml            # 只需一次
 *   node select-local.js           # 默认拉线上候选池，用默认 mihomo 内核探测
 *   MIHOMO_BIN=/path/to/mihomo node select-local.js
 *   node select-local.js --pool ./pool.yaml --out ./local
 *
 * 产物（默认 ./local/）：
 *   nodes.yaml     完整 mihomo 配置，客户端直接导入这个文件
 *   provider.yaml  只有 proxies:，给本地/自建服务端的 proxy-provider 用
 */
'use strict';

const fs = require('fs');
const path = require('path');
const YAML = require('js-yaml');

const f = require('./fetch.js');

const DEFAULT_POOL = 'https://node.lorcan.top/pool.yaml';
const DEFAULT_OUT = path.join(process.cwd(), 'local');

function arg(name, dflt) {
  const i = process.argv.indexOf('--' + name);
  return i > -1 && process.argv[i + 1] ? process.argv[i + 1] : dflt;
}

function writeYaml(file, doc, header) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, (header ? header + '\n' : '') + YAML.dump(doc, { lineWidth: 200, noRefs: true }));
}

async function loadPool(src) {
  const fsLib = require('fs');
  let text;
  if (/^https?:\/\//i.test(src)) {
    text = await f.fetchText(src, 30000);
  } else {
    // 本地文件（相对/绝对路径都行），方便先拿一份池子离线试
    const local = path.resolve(src);
    if (!fsLib.existsSync(local)) throw new Error(`候选池文件不存在: ${local}`);
    text = fsLib.readFileSync(local, 'utf8');
  }
  const proxies = f.parseProxyPayload(text);
  if (!proxies.length) throw new Error(`候选池里没有节点: ${src}`);
  return proxies;
}

async function main() {
  const poolSrc = arg('pool', process.env.POOL_URL || DEFAULT_POOL);
  const outDir = path.resolve(arg('out', DEFAULT_OUT));

  // 本机（尤其国内家宽）到境外节点的往返远高于机房：默认阈值放宽，
  // 否则「能连但慢」的节点会被一刀切掉。显式设了环境变量则以环境变量为准。
  if (!process.env.MAX_DELAY) f.CFG.maxDelayMs = 2000;
  if (!process.env.PROBE_TIMEOUT) f.CFG.probeTimeoutMs = 5000;

  console.log(`[local] 候选池: ${poolSrc}`);
  const raw = await loadPool(poolSrc);
  console.log(`[local] 池内节点: ${raw.length}`);

  // 池里的名字形如 🇺🇸US-003，区域信息随名字带过来，先把标签取出来
  const entries = [];
  for (const node of raw) {
    const proxy = f.sanitizeNode(node);
    if (!proxy) continue;
    entries.push({
      proxy,
      region: f.regionTag(node.name || ''),
      key: f.dedupeKey(proxy),
    });
  }
  const uniq = f.dedupe(entries);
  console.log(`[local] 规范化后: ${entries.length}，去重后: ${uniq.length}`);

  if (!uniq.length) throw new Error('候选池清洗后为空');

  const probed = await f.probeAll(uniq);
  console.log(`[local] 本机通过探测: ${probed.length}/${uniq.length}`);

  const kept = f.rank(probed);
  if (!kept.length) throw new Error('没有节点通过本机探测，检查网络或放宽 MAX_DELAY');

  const names = f.nameNodes(kept);
  const proxies = kept.map((item, i) => ({ ...item.proxy, name: names[i] }));

  const header = [
    `# generated by select-local.js at ${new Date().toISOString()}`,
    `# nodes: ${proxies.length} · 由本机网络实测 · probe: ${f.CFG.probeUrl} (expect ${f.CFG.probeExpected})`,
  ].join('\n');

  const outClient = path.join(outDir, 'nodes.yaml');
  const outProvider = path.join(outDir, 'provider.yaml');
  writeYaml(outClient, f.buildClientDoc(proxies), header);
  writeYaml(outProvider, f.buildProviderDoc(proxies), header);

  const dist = {};
  for (const item of kept) dist[item.region] = (dist[item.region] || 0) + 1;
  console.log(
    `[local] 区域: ${Object.entries(dist)
      .sort((a, b) => b[1] - a[1])
      .map(([k, v]) => `${k}:${v}`)
      .join(' ')}`
  );
  console.log(
    `[local] 延迟: 最快 ${kept[0].delay}ms / 最慢 ${kept[kept.length - 1].delay}ms`
  );
  console.log(`[local] 产出: ${outClient}`);
  console.log(`[local]       ${outProvider}`);
  console.log('[local] 客户端「订阅/配置」里导入 nodes.yaml 即可，不依赖线上订阅');
}

if (require.main === module) {
  main().catch((e) => {
    console.error('[local] 失败:', e.message);
    process.exit(1);
  });
}
